it('reviews the exact proposed content then requires a separate apply approval', async () => {
  const execute = vi.spyOn(api, 'executeStudioTool')
    .mockResolvedValueOnce({ status: 'success', detail: '', result: { entries: [{ path: 'math.py', name: 'math.py', directory: false }] } })
    .mockResolvedValueOnce({ status: 'success', detail: '', result: { path: 'math.py', content: 'return a-b', sha256: 'a'.repeat(64) } })
    .mockResolvedValueOnce({ status: 'success', detail: '', result: { change_id: 'b'.repeat(32), path: 'math.py', proposal_sha256: 'c'.repeat(64), diff: '-return a-b\n+return a+b' } })
    .mockResolvedValueOnce({ status: 'approval_required', detail: '', result: null, approval: { request_id: 'apply-grant', preview: { policy_revision: 1 } } })
  const approve = vi.spyOn(api, 'decideApproval').mockResolvedValue({} as api.ApprovalItem)
  const consume = vi.spyOn(api, 'continueStudioTool').mockResolvedValue({ status: 'success', detail: '', result: { status: 'applied', sha256: 'd'.repeat(64) } })
  render(<CodingStudio projectId="alpha" authenticated />)
  fireEvent.click(await screen.findByRole('button', { name: 'File: math.py' }))
  fireEvent.change(await screen.findByLabelText('Proposed file content'), { target: { value: 'return a+b' } })
  fireEvent.click(screen.getByRole('button', { name: 'Review proposed patch' }))
  await screen.findByText('Exact diff')
  expect(execute).toHaveBeenLastCalledWith('studio_propose', { path: 'math.py', before_sha256: 'a'.repeat(64), content: 'return a+b' }, 'alpha')
  expect(approve).not.toHaveBeenCalled()
  fireEvent.click(screen.getByRole('button', { name: 'Request apply approval' }))
  fireEvent.click(await screen.findByRole('button', { name: 'Approve exact patch' }))
  await screen.findByText(`Applied and verified. SHA-256: ${'d'.repeat(64)}`)
  expect(approve).toHaveBeenCalledWith('apply-grant', true, 'alpha')
  expect(consume).toHaveBeenCalledWith('apply-grant', 'alpha')
  expect(screen.getByRole('button', { name: 'Request checkpoint rollback' })).toBeInTheDocument()
})

