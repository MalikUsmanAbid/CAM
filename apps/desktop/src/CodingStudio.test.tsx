it('does not disclose a late file response from the previous project', async () => {
  let finish: (value: api.StudioResult) => void = () => undefined
  vi.spyOn(api, 'executeStudioTool').mockImplementation(async (name, _, project) => {
    if (name === 'studio_read') return new Promise((resolve) => { finish = resolve })
    return { status: 'success', detail: '', result: { entries: project === 'alpha' ? [{ path: 'private.py', name: 'private.py', directory: false }] : [] } }
  })
  const { rerender } = render(<CodingStudio key="alpha" projectId="alpha" authenticated />)
  fireEvent.click(await screen.findByRole('button', { name: 'File: private.py' }))
  rerender(<CodingStudio key="beta" projectId="beta" authenticated />)
  await act(async () => { finish({ status: 'success', detail: '', result: { path: 'private.py', content: 'alpha private content' } }) })
  expect(screen.queryByText('alpha private content')).not.toBeInTheDocument()
  expect(screen.queryByText('private.py')).not.toBeInTheDocument()
})
