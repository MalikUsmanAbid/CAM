it('displays the actual model-proposed content and diff without automatically applying it', async () => {
  const execute = vi.spyOn(api, 'executeStudioTool')
    .mockResolvedValueOnce({ status: 'success', detail: '', result: { entries: [{ path: 'math.py', name: 'math.py', directory: false }] } })
    .mockResolvedValueOnce({ status: 'success', detail: '', result: { path: 'math.py', content: 'return a-b', sha256: 'original' } })
    .mockResolvedValueOnce({ status: 'success', detail: '', result: { change_id: 'model', path: 'math.py', proposal_sha256: 'proposal', before_exists: true, content: 'return a+b', diff: '-return a-b\n+return a+b' } })
  render(<CodingStudio projectId="alpha" authenticated />)
  fireEvent.click(await screen.findByRole('button', { name: 'File: math.py' }))
  await screen.findByLabelText('Proposed file content')
  fireEvent.change(screen.getByLabelText('AI coding request'), { target: { value: 'Fix addition' } })
  fireEvent.change(screen.getByLabelText('Additional context paths'), { target: { value: 'README.md\ncontext.txt' } })
  fireEvent.click(screen.getByRole('button', { name: 'Ask AI for reviewed patch' }))
  expect(await screen.findByText('Exact diff')).toBeInTheDocument()
  expect(screen.getByLabelText('Proposed file content')).toHaveValue('return a+b')
  expect(execute).toHaveBeenLastCalledWith('studio_ai_propose', { path: 'math.py', before_sha256: 'original', request: 'Fix addition', context_paths: ['README.md', 'context.txt'] }, 'alpha')
  expect(execute).not.toHaveBeenCalledWith('studio_apply', expect.anything(), expect.anything())
  expect(screen.getByRole('button', { name: 'Request apply approval' })).toBeInTheDocument()
})

